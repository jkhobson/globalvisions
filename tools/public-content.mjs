// Makes js/content/<pack>-public.js for every content pack: the questions WITHOUT the answer key, for school mode.
// The full js/content/<pack>.js (right option first, reasons, explanations, traps, jumble order) is only used in
// demo mode and to make supabase/content.sql. It is never put on the school website, so students can't read the answers.
// Run after changing content:
//   node tools/public-content.mjs
// A test checks the files are up to date.
import { writeFileSync } from "node:fs";
import { PACKS } from "../js/content/worlds.js";

// Options (and jumble sentences) are listed in alphabetical order, which says nothing about which is right.
// The server stores its key in the same order, so a tap is sent as a position in this list.
const alpha = list => list.map((o, k) => ({ ...o, k })).sort((a, b) => a.t.localeCompare(b.t, "en"));
export const publicOrder = it => alpha(it.options);
export const publicParts = it => alpha(it.parts);
export const loadPack = name => import(`../js/content/${name}.js`);

export async function publicJS(name) {
  const P = await loadPack(name);
  const items = P.ITEMS.map(it => ({ id: it.id, block: it.block, demand: it.demand, ...(it.kind ? { kind: it.kind } : {}),
    ...(it.source ? { source: it.source } : {}), stem: it.stem, hint: it.hint,
    ...(it.kind === "order" ? { parts: publicParts(it).map(o => ({ t: o.t })) } : { options: publicOrder(it).map(o => ({ t: o.t })) }) }));
  const j = v => JSON.stringify(v, null, 1);
  return [`// Generated by tools/public-content.mjs from js/content/${name}.js. Do not edit by hand.`,
    "// No answer key here: in school mode the server says whether a choice is right.",
    "export const PUBLIC = true;",
    `export const GLOSSARY = ${j(P.GLOSSARY)};`, `export const SOURCES = ${j(P.SOURCES)};`, `export const ITEMS = ${j(items)};`,
    `export const MISSION = ${j(P.MISSION)};`,
    ...(P.TRUST_CARDS ? [`export const TRUST_CARDS = ${j(P.TRUST_CARDS.map(c => ({ t: c.t, d: c.d })))};`] : []), ""].join("\n");
}
if (import.meta.url === `file://${process.argv[1]}`) {
  for (const name of PACKS) writeFileSync(new URL(`../js/content/${name}-public.js`, import.meta.url), await publicJS(name));
}
