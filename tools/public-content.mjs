// Makes js/content/fizz-public.js: the questions WITHOUT the answer key, for school mode.
// The full js/content/fizz.js (right option first, reasons, explanations, traps) is only used in demo mode
// and to make supabase/content.sql. It is never put on the school website, so students can't read the answers.
// Run after changing content:
//   node tools/public-content.mjs > js/content/fizz-public.js
// A test checks the file is up to date.
import { GLOSSARY, SOURCES, ITEMS, MISSION, TRUST_CARDS } from "../js/content/fizz.js";

// Options are listed in alphabetical order, which says nothing about which one is right.
// The server stores its key in the same order, so a tap is sent as a position in this list.
export const publicOrder = it => it.options.map((o, k) => ({ ...o, k })).sort((a, b) => a.t.localeCompare(b.t, "en"));

export function publicJS() {
  const items = ITEMS.map(it => ({ id: it.id, block: it.block, demand: it.demand, ...(it.source ? { source: it.source } : {}),
    stem: it.stem, hint: it.hint, options: publicOrder(it).map(o => ({ t: o.t })) }));
  const cards = TRUST_CARDS.map(c => ({ t: c.t, d: c.d }));
  const j = v => JSON.stringify(v, null, 1);
  return ["// Generated by tools/public-content.mjs from js/content/fizz.js. Do not edit by hand.",
    "// No answer key here: in school mode the server says whether a choice is right.",
    "export const PUBLIC = true;",
    `export const GLOSSARY = ${j(GLOSSARY)};`, `export const SOURCES = ${j(SOURCES)};`, `export const ITEMS = ${j(items)};`,
    `export const MISSION = ${j(MISSION)};`, `export const TRUST_CARDS = ${j(cards)};`, ""].join("\n");
}
if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(publicJS());
