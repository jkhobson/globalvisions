// Makes supabase/content.sql from the app's content: each question's skill step, difficulty, which option is right,
// the reason each wrong option is wrong, and the explanation. This is the answer key: only the server holds it in school mode.
// Run after changing content:
//   node tools/content-sql.mjs > supabase/content.sql
// A test checks the file is up to date. Options are stored in the same (alphabetical) order as js/content/<pack>-public.js.
// Sentence jumbles store the right order (as positions in the public list) and, for each place in the order, the reason
// shown when a student puts the wrong sentence there.
import { BLOCKS } from "../js/content/curriculum.js";
import { PACKS } from "../js/content/worlds.js";
import { publicOrder, publicParts, loadPack } from "./public-content.mjs";

const q = s => `'${String(s).replace(/'/g, "''")}'`;
export async function contentSQL() {
  const packs = await Promise.all(PACKS.map(loadPack));
  const out = ["-- Generated by tools/content-sql.mjs. Do not edit by hand. Run in Supabase after schema.sql and progress.sql.", "begin;",
    "delete from public.items; delete from public.trust_cards; delete from public.blocks;"];
  for (const [id, b] of Object.entries(BLOCKS)) out.push(`insert into public.blocks (id, needs) values (${q(id)}, array[${b.needs.map(q).join(", ")}]::text[]);`);
  for (const it of packs.flatMap(p => p.ITEMS)) {
    if (it.kind === "order") {
      const pub = publicParts(it), seq = it.parts.map((_, k) => pub.findIndex(o => o.k === k));
      out.push(`insert into public.items (id, block, demand, options, explain, seq, steps) values (${q(it.id)}, ${q(it.block)}, ${it.demand}, '[]'::jsonb, ${q(it.explain)}, array[${seq.join(", ")}]::int[], ${q(JSON.stringify(it.parts.map(p => p.why)))}::jsonb);`);
      continue;
    }
    const opts = JSON.stringify(publicOrder(it).map(o => ({ right: o.k === 0, trap: o.trap || null, b: o.b || null, why: o.why || null })));
    out.push(`insert into public.items (id, block, demand, options, explain) values (${q(it.id)}, ${q(it.block)}, ${it.demand}, ${q(opts)}::jsonb, ${q(it.explain)});`);
  }
  const cards = packs.find(p => p.TRUST_CARDS).TRUST_CARDS;
  cards.forEach((c, i) => out.push(`insert into public.trust_cards (idx, ok, trap, why) values (${i}, ${c.ok}, ${c.trap ? q(c.trap) : "null"}, ${q(c.why)});`));
  out.push("commit;");
  return out.join("\n") + "\n";
}
if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(await contentSQL());
